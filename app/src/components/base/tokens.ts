/**
 * base/ 共通のデザイン語彙
 *
 * 部品ごとに色やサイズの言葉がばらつくと、画面の統一感が崩れるうえ
 * 「同じ意味なのに名前が違う」状態になる。語彙はここだけで定義する。
 *
 * - 色は必ず `tone`（意味）で受け取る。`color="red"` のような生の色名は作らない
 * - `variant` は形（塗り・枠線・透明）だけを表す。色の意味を持たせない
 * - `size` は sm / md / lg を基本とする
 */

/** 用途を表す色。実際の配色は各部品が持つ */
export type Tone =
    /** 中立・無効・キャンセル済み */
    | "neutral"
    /** 主要操作・確定・進行中（既定の青） */
    | "info"
    /** 完了・正常 */
    | "success"
    /** 要対応・残りわずか */
    | "warning"
    /** エラー・満席・取り消しなどの破壊的操作 */
    | "danger"

/** 見た目の型。色ではなく「塗るか・枠線か・透明か」だけを表す */
export type Variant =
    /** 塗りつぶし */
    | "filled"
    /** 枠線のみ */
    | "outlined"
    /** 淡い塗り（背景に薄く色を敷く） */
    | "soft"
    /** 背景も枠線も持たない */
    | "ghost"

/** 大きさ。幅の段階が必要な Modal・Drawer・Avatar だけは独自の語彙を持つ */
export type Size = "sm" | "md" | "lg"

/**
 * 重なり順
 *
 * 数値を各所に散らすと前後関係が読めなくなるため、ここで一覧にする。
 * **Tailwind のクラス名（`z-50` など）で指定するときは必ず定数リテラルで書くこと。**
 * `z-${zIndex}` のような動的なクラス名は生成されず、重なり順が丸ごと効かなくなる。
 * 値を props で変えられるようにする場合は `style={{ zIndex }}` を使う。
 */
export const Z_INDEX = {
    /** ページ内で浮かせる要素（タイムテーブルの予定ブロックなど） */
    raised: 10,
    /** 共通ヘッダー */
    header: 40,
    /** 画面を覆うもの（Modal / Drawer） */
    overlay: 50,
    /** ツールチップ。覆うものより前に出す */
    tooltip: 60,
    /** 処理中の全画面ローディング。最前面 */
    loading: 70,
} as const
